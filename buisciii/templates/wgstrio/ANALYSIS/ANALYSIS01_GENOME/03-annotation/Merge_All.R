#!/usr/bin/env Rscript
# ============================================================================
# Merge_All.R
# ----------------------------------------------------------------------------
# OBJECTIVE:
#   Combine four sources of data into one final annotated variant table:
#     1. VEP annotations (header + variants)        (vep/vep_annot_head.txt)
#     2. dbNSFP variant-level annotations           (dbNSFP_ENSG_plugin_hg38.txt)
#     3. dbNSFP gene-level annotations              (dbNSFP_ENSG_gene_GRCh38.txt)
#     4. Variant/genotype table (w/o annotations)   (vep/variants.table)
#
#   The script performs the following three joins in sequence, producing intermediate outputs:
#     JOIN 1  VEP            LEFT JOIN  dbNSFP variants   on the variant key
#     JOIN 2  that result    LEFT JOIN  dbNSFP genes      on Gene
#     JOIN 3  that result    INNER JOIN variants.table    on the original ID
#
# WORKFLOW:
# 1. A subset of the dbNSFP variants table (plugin) is generated by selecting only those variants indicated in variants.table
#    generating a subtable called dbNSFP_case.txt.
# 2. Such subtable is loaded in RAM along with the dbNSFP genes table and variants.table.
# 3. The VEP annotation table is then loaded in chunks and the aforementioned joins are performed.
# 4. If all joins are successful, a merged variants_annot_all.tab final table is generated, including all identified variants
#    along with their VEP annotations and additional columns from dbNSFP (variants without a VEP annotation are not included).
#
# MEMORY STRATEGY:
#   The whole dbNSFP v5.4 table does NOT fit in RAM. This script:
#     - streams dbNSFP once with AWK (by means of subset_dbnsfp.awk) and keeps only the
#       rows whose variant key appears in variants.table;
#     - reads VEP in chunks instead of loading the whole file.
#   Gene annotations and variants.table are still fully loaded in memory;
#   since they are smaller than dbNSFP's variant-level annotations file.
#
# INPUTS:
#   vep/variants.table               Variant/genotype table (must have ID).
#   vep/vep_annot_head.txt           VEP output, header + rows, must have ID column.
#   dbNSFP_ENSG_plugin_hg38.txt      dbNSFP variant annotations (GRCh38).
#   dbNSFP_ENSG_gene_GRCh38.txt      dbNSFP gene annotations (GRCh38).
#   subset_dbnsfp.awk                Helper script.
#
# OUTPUTS:
#   vep/vep_plugin.txt               VEP table + dbNSFP variants.
#   vep/vep_dbNSFP.txt               Previous result + dbNSFP genes.
#   variants_annot_all.tab           Previous result + variants.table --> final table.
#   vep/dbNSFP_case.txt              dbNSFP subset used (only for traceability).
#
#   Bear in mind that the three intermediate VEP outputs only contain annotations for IDs that
#   also appear in variants.table, because the final INNER join would discard
#   the rest anyway.
#
# USAGE:
#   From the 03-annotation directory:
#     Rscript Merge_All.R [rows_per_chunk]
#
#   rows_per_chunk counts INPUT VEP ROWS (default 50000, it is not mandatory
#   to indicate this number when running the script). You can lower it if you hit
#   memory limits in the joins.
#
# ENVIRONMENT VARIABLES:
#   SLURM_CPUS_PER_TASK      Number of data.table threads (default 1).
#   MERGE_MAX_BLOCK_ROWS     Max predicted rows per join block (default 1e6).
#                            Lower it to fail fast on duplicate-key expansion.
#
# ============================================================================

suppressPackageStartupMessages(library(data.table))

# --- CONFIGURATION -----------------------------------------------------------
# Three settings control how the script runs. All have sensible defaults, so
# you only need to touch them if you hit memory or CPU problems.

# SETTING 1: chunk size (command-line argument)
# VEP is read in blocks of this many ROWS (default 50000), not all at once.
# Rows, not variants: one variant takes several rows (one per transcript).
# A variant split across two chunks is fine, because every join below is
# row-wise: each row is resolved on its own, independently of its neighbours.
# If you run out of RAM, lower it:
#     Rscript Merge_All.R 20000
args <- commandArgs(trailingOnly=TRUE)
chunk_rows <- if (length(args)) as.integer(args[1]) else 50000L
if (is.na(chunk_rows) || chunk_rows < 1L) stop("Invalid block size")

# SETTING 2: CPU threads (set automatically by Slurm)
# Use only the CPUs Slurm allocated to this job (SLURM_CPUS_PER_TASK), or
# 1 thread outside Slurm. Without this, data.table would grab every core of
# the node.
threads <- as.integer(Sys.getenv("SLURM_CPUS_PER_TASK", "1"))
setDTthreads(if (is.na(threads)) 1L else max(1L, threads))

# SETTING 3: safety brake on join size (environment variable)
# Joining on repeated keys multiplies rows: 2 dbNSFP rows x 3 gene rows = 6
# output rows per VEP row. With heavily duplicated keys, one chunk could blow
# up to hundreds of millions of rows and exhaust memory.
# Before each join, guard() predicts the output size; if it exceeds this
# limit (default 1e6 rows), the script stops BEFORE building the table.
max_rows <- as.numeric(Sys.getenv("MERGE_MAX_BLOCK_ROWS", "1000000"))
if (!is.finite(max_rows) || max_rows < 1) stop("Invalid MERGE_MAX_BLOCK_ROWS")

# --- HELPER FUNCTIONS -----------------------------------------------------------------

logmsg <- function(...) message(format(Sys.time(), "%F %T"), " | ", ...)

# required(): fail if a table lacks columns we depend on, since it is better to stop
# here with a clear message than to run a join on a wrong or
# malformed file and silently get empty or misleading results.
required <- function(x, columns, label) {
    missing <- setdiff(columns, names(x))   # needed columns the table doesn't have
    if (length(missing)) stop(label, ": missing columns ", paste(missing, collapse=", "))
}

# read_table(): read a TSV with EVERY column as text, so that every value is exactly as written in the file.
#   quote=""          : no quote handling, so a stray " in a description is
#                       just text, not the start of a quoted field.
#   na.strings="NA"   : only the literal NA counts as missing. '-' and '.' stay
#                       as normal text (missing values are WRITTEN as '-' later).
#   check.names=TRUE  : turn column names into valid R names (spaces -> dots).
read_table <- function(path) {
    fread(file=path, sep="\t", quote="", header=TRUE, check.names=TRUE,
          colClasses="character", na.strings="NA", showProgress=FALSE)
}

# guard(): abort if a join is predicted to be too big and will cause OOM error.
# Called BEFORE each merge, so we never try to build the huge table.
# We stop rather than deduplicate or truncate annotations: silently losing
# data would be worse than failing loudly.
guard <- function(n, label) {
    if (n > max_rows)
        stop(label, ": there are ", n, " expected rows in a block. Reduce chunk size",
             "and re-run, or check for duplicate keys in the input tables.")
}

counts <- function(x, key) x[, .(matches=.N), by=key]

# expected_left(): predict how many rows a LEFT JOIN will produce.
# Each row of x yields one output row per matching lookup row, or exactly ONE
# row if nothing matches (a left join keeps unmatched rows).
# Example: keys with 2, 0 and 3 matches -> 2 + 1 + 3 = 6 output rows.
# as.double avoids integer overflow when the total is large.
expected_left <- function(x, key, lookup) {
    n <- lookup$matches[match(x[[key]], lookup[[key]])]   # matches per row (NA = none)
    n[is.na(n)] <- 1                                      # no match -> still 1 row
    sum(as.double(n))
}

# write_part(): write a chunk's result to disk, building one file over time.
# First chunk: create the file WITH a header. Later chunks: append WITHOUT one,
# so the final file has a single header. R NA is written as '-'.
# Each chunk is sorted on its own, so the final file is NOT globally sorted.
write_part <- function(x, path, first) {
    fwrite(x, path, sep="\t", quote=FALSE, na="-", append=!first, col.names=first)
}

# normalise_id(): chromosome nomenclature normalisation
normalise_id <- function(id) sub("^M_", "MT_", sub("^chr", "", id))

# --- MAIN --------------------------------------------------------------------

main <- function() {
    script_arg <- grep("^--file=", commandArgs(), value=TRUE)
    script_dir <- dirname(normalizePath(sub("^--file=", "", script_arg[1])))
    awk_script <- file.path(script_dir, "subset_dbnsfp.awk")

    plugin_file  <- "dbNSFP_ENSG_plugin_hg38.txt"
    gene_file    <- "dbNSFP_ENSG_gene_GRCh38.txt"
    variant_file <- "vep/variants.table"
    vep_file     <- "vep/vep_annot_head.txt"

    for (path in c(awk_script, plugin_file, gene_file, variant_file, vep_file)) {
        if (!file.exists(path) || file.info(path)$size == 0)
            stop("Is missing or empty: ", path)
    }

    # Work in a hidden temporary directory ("staging area") instead of writing
    # straight to the final files. This avoids leaving a mixture of old and new outputs if the script fails partway through.
    # The directory is removed at the end.
    # The final output files are written only after every chunk has completed successfully.
    stage <- tempfile(pattern=".merge_all_", tmpdir=".")
    dir.create(stage)
    logmsg("Temporal directory: ", stage)

    # ------------------------------------------------------------------------
    # STEP 1. Preselect dbNSFP rows for the case.
    # ------------------------------------------------------------------------
    # Shrink dbNSFP before loading it into R.
    #
    # The full dbNSFP file is far too large for RAM, but this case only needs
    # the rows for ITS variants. So awk reads dbNSFP once, line by line (it
    # never holds the file in memory), and keeps only rows whose variant key
    # appears in variants.table.
    subset_file <- file.path(stage, "dbNSFP_case.txt") # This table will contain all dbNSFP records but only from the variants listed in variants.table
    logmsg("Selecting dbNSFP records of interest...")
    status <- system2("awk", c("-f", shQuote(awk_script), shQuote(variant_file),
                              shQuote(plugin_file)), stdout=subset_file)
    if (status != 0L) stop("Failed selecting dbNSFP; error code: ", status)

    # ------------------------------------------------------------------------
    # STEP 2. Load the smaller dbNSFP table, then the gene and case tables.
    # ------------------------------------------------------------------------
    # The dbNSFP subset is small enough to fit in RAM, so we can read it all at once.
    # Relevant columns from the dbNSFP plugin table are selected.
    plugin <- read_table(subset_file)
    required(plugin, c("chr", "hg38_pos", "ref", "alt"), "dbNSFP")
    plugin[, DBNSFP_KEY := normalise_id(paste(chr, hg38_pos, ref, alt, sep="_"))]
    plugin[, c("chr", "hg38_pos", "ref", "alt") := NULL]
    plugin_counts <- counts(plugin, "DBNSFP_KEY")
    setkeyv(plugin, "DBNSFP_KEY")

    # Gene-level annotations from the dbNSFP gene table.
    genes <- read_table(gene_file)
    required(genes, c("Gene", "OMIM_id", "Function_description",
                      "Disease_description", "HPO_id", "HPO_name"), "Genes")
    if (!nrow(genes)) stop("The genes table only contains a header")
    gene_counts <- counts(genes, "Gene")
    setkeyv(genes, "Gene")

    # Variants table.
    variants <- read_table(variant_file)
    required(variants, "ID", "variants.table")
    if (!nrow(variants)) stop("variants.table does not contain any variants")
    if (anyNA(variants$ID) || any(variants$ID %in% c("", ".")))
        stop("Empty ID in variants.table")
    if (anyDuplicated(variants$ID))
        stop("Duplicated ID in variants.table; IDs must be unique")
    setkeyv(variants, "ID")

    logmsg("In RAM: dbNSFP of case=", nrow(plugin), "; genes=", nrow(genes),
           "; variants=", nrow(variants))
    logmsg("Keys with multiple rows: dbNSFP=", sum(plugin_counts$matches>1),
           "; genes=", sum(gene_counts$matches>1),
           ". All their rows will be kept in the output, so the final table may have more rows than variants.")

    # ------------------------------------------------------------------------
    # STEP 3. Open VEP once, validate the header and process chunk by chunk.
    # ------------------------------------------------------------------------
    con <- file(vep_file, open="rt")
    on.exit(close(con), add=TRUE)
    header <- readLines(con, n=1L, warn=FALSE)
    if (!length(header)) stop("VEP has no header")
    header_dt <- fread(text=paste0(header, "\n"), sep="\t", quote="", header=TRUE,
                       check.names=TRUE, colClasses="character", na.strings="NA")
    required(header_dt, c("ID", "Gene"), "VEP")
    expected_names <- names(header_dt)

    block     <- 0L
    total_in  <- 0
    total_out <- 0

    repeat {
        lines <- readLines(con, n=chunk_rows, warn=FALSE)
        if (!length(lines)) break
        if (any(!nzchar(lines))) stop("Empty line in VEP table; check input")
        block <- block + 1L

        text <- paste(c(header, lines), collapse="\n")
        vep <- fread(text=paste0(text, "\n"), sep="\t", quote="", header=TRUE,
                     check.names=TRUE, fill=TRUE, colClasses="character",
                     na.strings="NA", showProgress=FALSE)
        if (!identical(names(vep), expected_names) || nrow(vep)!=length(lines))
            stop("Unexpected structure in VEP block ", block)
        if (anyNA(vep$ID) || any(vep$ID %in% c("", "."))) stop("Empty ID in VEP")
        total_in <- total_in + nrow(vep)
        rm(lines, text)

        # --- JOIN 1: VEP LEFT JOIN dbNSFP variants ---------------------------
        # Keep all VEP rows and add every dbNSFP row matching DBNSFP_KEY.
        # A missing match produces NA annotation cells, written as '-'.
        vep[, DBNSFP_KEY := normalise_id(ID)]
        guard(expected_left(vep, "DBNSFP_KEY", plugin_counts), "Union dbNSFP")
        joined <- merge(vep, plugin, by="DBNSFP_KEY", all.x=TRUE,
                        sort=TRUE, allow.cartesian=TRUE)
        joined[, DBNSFP_KEY := NULL]
        rm(vep)
        write_part(joined, file.path(stage, "vep_plugin.txt"), block==1L)

        # --- JOIN 2: previous result LEFT JOIN dbNSFP genes ------------------
        # Keep every row above and attach annotations by gene.
        guard(expected_left(joined, "Gene", gene_counts), "Union genes")
        with_genes <- merge(joined, genes, by="Gene", all.x=TRUE,
                            sort=TRUE, allow.cartesian=TRUE)
        rm(joined)
        write_part(with_genes, file.path(stage, "vep_dbNSFP.txt"), block==1L)

        # --- JOIN 3: previous result INNER JOIN variants.table ---------------
        # Attach the previous result to the original variant/genotype table, keeping only IDs that appear in both.
        # This is the final output.
        genotype_subset <- variants[.(unique(with_genes$ID)), nomatch=0L]
        final <- merge(genotype_subset, with_genes, by="ID", all=FALSE,
                       sort=TRUE, allow.cartesian=TRUE)
        write_part(final, file.path(stage, "variants_annot_all.tab"), block==1L)
        total_out <- total_out + nrow(final)

        # Counts refer to table rows, not distinct variants or selected genes.
        logmsg("Block ", block, ": VEP accumulated=", total_in,
               "; final rows accumulated=", total_out)

        rm(with_genes, genotype_subset, final)
        invisible(gc())
    }

    # Empty final results are rejected rather than published as a header-only file.
    if (!block || !total_out) stop("No final results; check IDs and inputs")

    # ------------------------------------------------------------------------
    # STEP 4. Publish only after every chunk has completed.
    # ------------------------------------------------------------------------
    logmsg("Publishing complete results")
    sources <- c("vep_plugin.txt", "vep_dbNSFP.txt",
                 "variants_annot_all.tab", "dbNSFP_case.txt")
    destinations <- c("vep/vep_plugin.txt", "vep/vep_dbNSFP.txt",
                      "variants_annot_all.tab", "vep/dbNSFP_case.txt")
    for (i in seq_along(sources)) {
        if (!file.rename(file.path(stage, sources[i]), destinations[i]))
            stop("Failed to publish ", destinations[i],
                 "; check permissions. Temporary: ", stage)
    }
    unlink(stage, recursive=TRUE)
    logmsg("MERGE_COMPLETED: ", total_in, " VEP rows; ",
           total_out, " final rows")
}

main()
